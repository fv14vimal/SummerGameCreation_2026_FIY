void Game_Play()
{
    // TODO:05 背景のスクロール
    /*
    課題）
        2枚の背景をスクロールさせていきます。

    手順）
    1.  for文を使って BACK_MAX 回ループし
        backs[0] と backs[1] の位置に速度を足しましょう。

    2.  背景が画面の左端から完全に消えたら、x座標に DxPlus::CLIENT_WIDTH × 2 を足して
        右端の次の位置に移動させましょう。

        ※ 2枚の背景をループさせることで、無限スクロールを実現できます。
    */
    // TODO_05
    

    // TODO:09 プレイヤーの落下
    /*
    課題）
        プレイヤーが重力で下に落ちるようにしましょう。

    手順）
    1.  定数 GRAVITY を定義し、player.velocity.y に加算してください。
        ※ 値は 0.5f を使いましょう。
    2.  velocity を position に足しましょう。

    解説）
        毎フレーム少しずつ落下速度が上がり、放物線のような動きになります。
    */
    // TODO_09
    

    // TODO:10 プレイヤーのジャンプ
    /*
    課題）
        プレイヤーにジャンプさせます。

    手順）
    1.  定数 JUMP_FORCE をソースコードの上の方で定義します。
        値は -12.0f

    2.  スペースキーが押されたら、playerのvelocityに{ 0, JUMP_FORCE }を代入します。

    3.  「スペースキーが押されたら」の条件に、「velocity.y が -5.0f よりも大きければ」という
        条件を追加します。

    4.  冒頭で定数 JUMP_INPUT_LIMIT = -5.0f を定義し、先ほどの -5.0f を書き換える。
    */
    // TODO_10
    

    // TODO:12 アニメーション用変数の初期設定
    /*
    課題）
        ジャンプアニメーションを再生するために、
        プレイヤーのアニメーション制御用変数を「初期設定」しましょう。

    前提条件）
        この処理は、ジャンプが発生したときにだけ行うべきなので、
        ジャンプの処理（velocity を変更する処理）の直後に書きます。

    手順）
        1.  上記のジャンプ処理の中で、animStepIndex を 0 に設定します。
            → animationStepの0番目から ということです。
        2.  animTimer を 0 に設定します。
            → アニメーションが始まったばかりなので、カウントは 0 にします。
        3.  spriteIndex に、現在のステップ（FLAP_ANIM[animStepIndex]）が示す
            spriteIndex を設定します。
            → 何番目のスプライトを使うかを指定します。
        4.  spriteID に playerID の spriteIndex 番目を設定します。
            → 実際に描画されるスプライトIDです。
    */


    // TODO:13 プレイヤーのアニメーション
    /*
    課題）
        プレイヤーのアニメーションを進行させましょう。

    概要）
        ジャンプ後の一定時間ごとにスプライト画像を切り替えることで、
        「パタパタ」するアニメーションを表現します。
        落下が始まると2コマ目のスプライトに固定させます。（0コマ目, 1コマ目, 2コマ目...）

    手順）
        1.  animTimer を 1 加算します。
            → 経過フレーム数を数えるためです。

        2.  FLAP_ANIM[player.animStepIndex].duration が -1 でないとき、
            → これは「無限にそのコマを表示し続ける」という意味なので、
               それ以外の場合のみ、下記のアニメーション処理を行います。

        3.  animTimer が duration を超えた場合、
            → 次のステップに進みます。

        4.  animStepIndex を 1 増やし、animTimer を 0 に戻します。

        5.  次のアニメーションステップを参照する前に、
            FLAP_ANIM の範囲を超えないよう、安全装置を入れてください。
            animStepIndex が FLAP_ANIM_STEP_MAX より大きくならないように制限します。

        6.  FLAP_ANIM の現在のステップから spriteIndex を取得して代入し、
            playerID から該当コマの spriteID を取得して設定しましょう。

        7.  プレイヤーが落下しているとき（velocity.y > 0）には、
            スプライトを強制的に 2コマ目（playerID[2]）に切り替えます。
            → 「落下時は羽ばたきやめてバサーっと落ちる」動きを表現するためです。

        8.  6.で使用した「2」を定数に変えておきましょう。
            定数名：PLAYER_FALL_FRAME_INDEX = 2
    */
    // TODO_13
    

}

