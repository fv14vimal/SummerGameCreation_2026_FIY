//----------------------------------------------------------------------
// 更新処理
//----------------------------------------------------------------------
void Game_Update()
{
    switch (gameState)
    {
        case 0: // フェードイン中
        {
            gameFadeTimer -= 1 / 60.0f;
            if (gameFadeTimer < 0.0f)
            {
                gameFadeTimer = 0.0f;
                gameState++;
            }
            break;
        }

        case 1: // 通常時
        {
            Game_Play();

            // BackSpaceキーが押されたらタイトルに戻す
            int input = DxPlus::Input::GetButtonDown(DxPlus::Input::PLAYER1);
            if (input & DxPlus::Input::BUTTON_SELECT)
            {
                gameState++;
            }
            break;
        }

        case 2: // フェードアウト中
        {
            gameFadeTimer += 1 / 60.0f;
            if (gameFadeTimer > 1.0f)
            {
                gameFadeTimer = 1.0f;
                nextScene = SceneTitle;
            }
            break;
        }
    }
}

